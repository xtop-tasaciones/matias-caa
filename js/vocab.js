export function buildDefaults() {
  const boards = BOARDS.map(b => ({ ...b }));
  const cards = [];
  for (const [boardId, list] of Object.entries(CARDS)) {
    list.forEach((row, pos) => {
      if (!row) return;
      const [id, label, emoji, color, o] = row;
      cards.push({
        id, boardId, pos, label, emoji, color,
        speak: o.s || '',
        type: o.folder ? 'folder' : 'word',
        link: o.link || null,
        q: o.q || '',
        hidden: false,
        image: null,
        audio: null,
      });
    });
  }
  const schedule = { items: DEFAULT_SCHEDULE.map(cardId => ({ cardId, done: false })), first: 'ru-colegio', then: 'ru-jugar', day: '' };
  return { boards, cards, schedule, choice: { ...DEFAULT_CHOICE } };
}
